#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_FILE="$ROOT_DIR/.fzvis_config"

# Load memorized configuration if available
if [ -f "$CONFIG_FILE" ]; then
  # shellcheck source=/dev/null
  . "$CONFIG_FILE"
fi

SPACK_ROOT="${SPACK_ROOT:-"$HOME/.fzvis/spack"}"
SPACK_REPO_DIR="${SPACK_REPO_DIR:-"$HOME/.fzvis/spack_packages"}"
FZVIS_ENV_DIR="${FZVIS_ENV_DIR:-""}"
FZVIS_HOST="${FZVIS_HOST:-0.0.0.0}"
FZVIS_PORT="${FZVIS_PORT:-10080}"
SPACK_LIBPRESSIO_SPEC="${SPACK_LIBPRESSIO_SPEC:-libpressio+python+sz3+zfp+fpzip+mgard ^openblas~fortran}"
SPACK_NODE_SPEC="${SPACK_NODE_SPEC:-node-js@20:}"
SPACK_NPM_SPEC="${SPACK_NPM_SPEC:-npm}"

FZVIS_SKIP_SPACK="${FZVIS_SKIP_SPACK:-0}"
FZVIS_SKIP_NODE="${FZVIS_SKIP_NODE:-0}"
FZVIS_SKIP_FRONTEND_BUILD="${FZVIS_SKIP_FRONTEND_BUILD:-0}"
FZVIS_NONINTERACTIVE="${FZVIS_NONINTERACTIVE:-0}"

need_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "Missing required command: $1" >&2
    exit 1
  fi
}

prompt_yes_no() {
  local prompt="$1"
  local default="${2:-Y}" # Y or N
  if [ "${FZVIS_NONINTERACTIVE:-0}" = "1" ]; then
    if [[ "$default" =~ ^[Yy]$ ]]; then return 0; else return 1; fi
  fi
  local prompt_suffix
  if [[ "$default" =~ ^[Yy]$ ]]; then
    prompt_suffix="[Y/n]"
  else
    prompt_suffix="[y/N]"
  fi
  while true; do
    local answer=""
    if ! read -rp "$prompt $prompt_suffix " answer; then
      answer="$default"
    fi
    answer="${answer:-$default}"
    case "$answer" in
      [Yy]* ) return 0 ;;
      [Nn]* ) return 1 ;;
      * ) echo "Please answer yes (y) or no (n)." ;;
    esac
  done
}

prompt_input() {
  local prompt="$1"
  local default="$2"
  if [ "${FZVIS_NONINTERACTIVE:-0}" = "1" ]; then
    echo "$default"
    return 0
  fi
  local answer=""
  if ! read -rp "$prompt [default: $default]: " answer; then
    answer="$default"
  fi
  answer="${answer:-$default}"
  echo "$answer"
}

resolve_path() {
  local p="$1"
  # Trim whitespace
  p="$(echo "$p" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
  # Expand leading tilde
  p="${p/#\~/$HOME}"
  # Resolve to absolute path
  if [ -d "$p" ]; then
    (cd "$p" && pwd)
  elif [ -d "$(dirname "$p")" ]; then
    echo "$(cd "$(dirname "$p")" && pwd)/$(basename "$p")"
  else
    echo "$p"
  fi
}

save_config() {
  cat > "$CONFIG_FILE" <<CONFEOF
# Auto-generated by install_fzvis.sh on $(date)
SPACK_ROOT="$SPACK_ROOT"
SPACK_REPO_DIR="$SPACK_REPO_DIR"
FZVIS_ENV_DIR="$FZVIS_ENV_DIR"
FZVIS_HOST="$FZVIS_HOST"
FZVIS_PORT="$FZVIS_PORT"
CONFEOF
  echo "[INFO] Configuration memorized in $CONFIG_FILE"
}

clone_or_update() {
  local repo_url="$1"
  local target_dir="$2"
  local branch="${3:-}"
  if [ -d "$target_dir/.git" ]; then
    echo "Updating repository in $target_dir..."
    git -C "$target_dir" fetch --depth 1 origin
    git -C "$target_dir" reset --hard FETCH_HEAD
    if [ -n "$branch" ]; then
      git -C "$target_dir" fetch --depth 1 origin "$branch"
      git -C "$target_dir" checkout "$branch" 2>/dev/null || git -C "$target_dir" checkout -B "$branch" FETCH_HEAD
      git -C "$target_dir" reset --hard FETCH_HEAD
    else
      git -C "$target_dir" fetch --depth 1 origin
      git -C "$target_dir" reset --hard FETCH_HEAD
    fi
  else
    echo "Cloning $repo_url to $target_dir..."
    if [ -n "$branch" ]; then
      git clone --depth 1 --branch "$branch" "$repo_url" "$target_dir"
    else
      git clone --depth 1 "$repo_url" "$target_dir"
    fi
  fi
}

need_cmd git
need_cmd python3

# ============================================================
# 1. Spack Setup
# ============================================================
echo
echo "============================================================"
echo " 1. Spack Setup"
echo "============================================================"

DETECTED_SPACK_ROOT=""
if command -v spack >/dev/null 2>&1; then
  DETECTED_SPACK_ROOT="$(spack location -r 2>/dev/null || dirname "$(dirname "$(command -v spack)")")"
elif [ -f "$SPACK_ROOT/share/spack/setup-env.sh" ]; then
  DETECTED_SPACK_ROOT="$SPACK_ROOT"
fi

SKIP_SPACK_INSTALL=0
if [ -n "$DETECTED_SPACK_ROOT" ] && [ -f "$DETECTED_SPACK_ROOT/share/spack/setup-env.sh" ]; then
  SPACK_ROOT="$DETECTED_SPACK_ROOT"
  echo "[INFO] Existing Spack installation detected at: $SPACK_ROOT"
  if prompt_yes_no "Use existing Spack and skip downloading/updating Spack?" "Y"; then
    SKIP_SPACK_INSTALL=1
  fi
fi

if [ "$SKIP_SPACK_INSTALL" != "1" ] && [ "$FZVIS_SKIP_SPACK" != "1" ]; then
  echo "Installing or updating Spack in $SPACK_ROOT..."
  clone_or_update "https://github.com/spack/spack.git" "$SPACK_ROOT"
fi

if [ -f "$SPACK_ROOT/share/spack/setup-env.sh" ]; then
  # shellcheck source=/dev/null
  . "$SPACK_ROOT/share/spack/setup-env.sh"
else
  echo "Error: Spack environment setup script not found at $SPACK_ROOT/share/spack/setup-env.sh" >&2
  exit 1
fi

echo
echo "Checking Libpressio Spack package repository..."
if spack repo list 2>/dev/null | grep -q "spack_packages" || [ -d "$SPACK_REPO_DIR/.git" ]; then
  echo "[INFO] Libpressio repository already detected at: $SPACK_REPO_DIR"
  if prompt_yes_no "Skip updating Libpressio Spack package repository?" "Y"; then
    SKIP_REPO_UPDATE=1
  else
    SKIP_REPO_UPDATE=0
  fi
else
  SKIP_REPO_UPDATE=0
fi

if [ "${SKIP_REPO_UPDATE:-0}" != "1" ]; then
  echo "Adding or updating libpressio Spack package repository in $SPACK_REPO_DIR..."
  clone_or_update "https://github.com/robertu94/spack_packages.git" "$SPACK_REPO_DIR"
  spack repo add "$SPACK_REPO_DIR" || true
fi

# ============================================================
# 2. Spack Environment Setup (fzvis-env)
# ============================================================
echo
echo "============================================================"
echo " 2. Spack Environment Configuration (fzvis-env)"
echo "============================================================"

PARENT_DIR="$(cd "$ROOT_DIR/.." && pwd)"
DEFAULT_EXISTING_ENV=""
if [ -n "$FZVIS_ENV_DIR" ] && [ -d "$FZVIS_ENV_DIR" ]; then
  DEFAULT_EXISTING_ENV="$FZVIS_ENV_DIR"
elif [ -d "$PARENT_DIR/.spack-env" ] || [ -f "$PARENT_DIR/spack.yaml" ]; then
  DEFAULT_EXISTING_ENV="$PARENT_DIR"
else
  DEFAULT_EXISTING_ENV="$ROOT_DIR/fzvis-env"
fi

CHOICE="2"
if [ "${FZVIS_NONINTERACTIVE:-0}" = "1" ]; then
  if [ -n "$FZVIS_ENV_DIR" ]; then
    CHOICE="2"
  else
    CHOICE="1"
  fi
else
  echo "Please choose an option for the Spack environment:"
  echo "  1) Create a new Spack environment"
  echo "  2) Use an existing Spack environment"
  if [ -n "$DEFAULT_EXISTING_ENV" ] && { [ -d "$DEFAULT_EXISTING_ENV/.spack-env" ] || [ -f "$DEFAULT_EXISTING_ENV/spack.yaml" ]; }; then
    DEFAULT_CHOICE="2"
    echo "[INFO] Detected existing environment candidate: $DEFAULT_EXISTING_ENV"
  else
    DEFAULT_CHOICE="1"
  fi
  while true; do
    input_choice=""
    if ! read -rp "Select option [1/2] [default: $DEFAULT_CHOICE]: " input_choice; then
      input_choice="$DEFAULT_CHOICE"
    fi
    input_choice="${input_choice:-$DEFAULT_CHOICE}"
    if [ "$input_choice" = "1" ] || [ "$input_choice" = "2" ]; then
      CHOICE="$input_choice"
      break
    else
      echo "Please enter 1 or 2."
    fi
  done
fi

if [ "$CHOICE" = "1" ]; then
  DEFAULT_NEW_DIR="$ROOT_DIR/fzvis-env"
  CHOSEN_DIR="$(prompt_input "Enter directory path for the new environment" "$DEFAULT_NEW_DIR")"
  FZVIS_ENV_DIR="$(resolve_path "$CHOSEN_DIR")"
  echo "Configuring new Spack environment at: $FZVIS_ENV_DIR"
  if [ ! -d "$FZVIS_ENV_DIR/.spack-env" ] && [ ! -f "$FZVIS_ENV_DIR/spack.yaml" ]; then
    mkdir -p "$FZVIS_ENV_DIR"
    spack env create -d "$FZVIS_ENV_DIR"
  else
    echo "[INFO] Environment already exists at $FZVIS_ENV_DIR."
  fi
else
  CHOSEN_DIR="$(prompt_input "Enter the location of the existing Spack environment" "$DEFAULT_EXISTING_ENV")"
  FZVIS_ENV_DIR="$(resolve_path "$CHOSEN_DIR")"

  if [ ! -d "$FZVIS_ENV_DIR/.spack-env" ] && [ ! -f "$FZVIS_ENV_DIR/spack.yaml" ]; then
    echo "[WARNING] '$FZVIS_ENV_DIR' does not contain '.spack-env' or 'spack.yaml'."
    if ! prompt_yes_no "Continue with this directory anyway?" "N"; then
      echo "Installation cancelled. Please check the environment path and retry."
      exit 1
    fi
  else
    echo "[INFO] Verified existing Spack environment at: $FZVIS_ENV_DIR"
  fi
fi

echo "Activating Spack environment at $FZVIS_ENV_DIR..."
spack env activate -d "$FZVIS_ENV_DIR"

# Ensure system pkg-config search paths (including multiarch directories) are in PKG_CONFIG_PATH
# This is required because Spack's pkgconf does not search /usr/lib/<triplet>/pkgconfig by default
ARCH_TRIPLET="$(gcc -dumpmachine 2>/dev/null || uname -m)-linux-gnu"
for pcdir in \
  "/usr/lib/$ARCH_TRIPLET/pkgconfig" \
  "/usr/lib64/pkgconfig" \
  "/usr/lib/pkgconfig" \
  "/usr/local/lib/pkgconfig" \
  "/usr/local/share/pkgconfig" \
  "/usr/share/pkgconfig"; do
  if [ -d "$pcdir" ]; then
    export PKG_CONFIG_PATH="${PKG_CONFIG_PATH:+$PKG_CONFIG_PATH:}$pcdir"
  fi
done

# Memorize the environment configuration early so it persists even if subsequent steps fail
save_config

# ============================================================
# 3. Spack Dependencies (libpressio, python, node-js)
# ============================================================
echo
echo "============================================================"
echo " 3. Spack Dependencies (libpressio, python, node-js)"
echo "============================================================"

LIBPRESSIO_FOUND=0
if spack find libpressio >/dev/null 2>&1; then
  LIBPRESSIO_FOUND=1
fi

SKIP_SPACK_PACKAGES=0
if [ "$LIBPRESSIO_FOUND" = "1" ]; then
  INSTALLED_SPEC="$(spack find libpressio 2>/dev/null | grep -E '^libpressio' | head -n 1 | tr -s ' ' || echo "libpressio")"
  echo "[INFO] libpressio is ALREADY INSTALLED in this environment: $INSTALLED_SPEC"
  if prompt_yes_no "Skip adding and installing Spack dependencies (libpressio, etc.)?" "Y"; then
    SKIP_SPACK_PACKAGES=1
  fi
else
  echo "[INFO] libpressio was NOT found in this environment."
  if ! prompt_yes_no "Add and install Spack dependencies ($SPACK_LIBPRESSIO_SPEC)?" "Y"; then
    SKIP_SPACK_PACKAGES=1
  fi
fi

if [ "$SKIP_SPACK_PACKAGES" != "1" ]; then
  echo "Adding dependencies to Spack environment..."
  spack add py-pip python@3.10: $SPACK_LIBPRESSIO_SPEC
  if [ "$FZVIS_SKIP_NODE" != "1" ] && ! command -v node >/dev/null 2>&1; then
    spack add "$SPACK_NODE_SPEC"
  fi
  if [ "$FZVIS_SKIP_NODE" != "1" ] && ! command -v npm >/dev/null 2>&1; then
    spack add "$SPACK_NPM_SPEC"
  fi
  echo "Installing Spack environment dependencies..."
  spack install
else
  echo "[INFO] Skipping Spack package installation."
fi

# ============================================================
# 4. Python Requirements (requirements.txt)
# ============================================================
echo
echo "============================================================"
echo " 4. Python Requirements (requirements.txt)"
echo "============================================================"

PYTHON_REQ_OK=0
MISSING_PKG=""
if ! MISSING_PKG="$(python -c '
reqs = ["flask", "flask_cors", "netCDF4", "numpy", "openai", "matplotlib", "pywt", "jwt", "dotenv", "cachetools", "scipy"]
for pkg in reqs:
    try:
        __import__(pkg)
    except Exception as e:
        print(f"{pkg} ({e})")
        sys.exit(1)
' 2>&1)"; then
  PYTHON_REQ_OK=0
else
  PYTHON_REQ_OK=1
fi

SKIP_PIP=0
if [ "$PYTHON_REQ_OK" = "1" ]; then
  echo "[INFO] All required Python packages from requirements.txt are ALREADY INSTALLED."
  if prompt_yes_no "Skip running 'pip install -r requirements.txt'?" "Y"; then
    SKIP_PIP=1
  fi
else
  echo "[INFO] Some Python requirements are not installed or failed to import:"
  if [ -n "$MISSING_PKG" ]; then
    echo "       Failed import: $MISSING_PKG"
  fi
  if ! prompt_yes_no "Install Python requirements via pip?" "Y"; then
    SKIP_PIP=1
  fi
fi

if [ "$SKIP_PIP" != "1" ]; then
  echo "Installing Python requirements into Spack environment..."
  python -m ensurepip --upgrade >/dev/null 2>&1 || true
  python -m pip install --upgrade pip || true
  python -m pip install -r "$ROOT_DIR/requirements.txt" || true
else
  echo "[INFO] Skipping Python pip installation."
fi

# ============================================================
# 5. Frontend Dependencies & Build
# ============================================================
echo
echo "============================================================"
echo " 5. Frontend Dependencies & Build"
echo "============================================================"

SKIP_FRONTEND=0
if [ "$FZVIS_SKIP_FRONTEND_BUILD" = "1" ]; then
  SKIP_FRONTEND=1
  echo "[INFO] Frontend build skipped via FZVIS_SKIP_FRONTEND_BUILD=1"
elif [ -f "$ROOT_DIR/dist/index.html" ]; then
  echo "[INFO] Production frontend build ALREADY EXISTS at $ROOT_DIR/dist."
  if prompt_yes_no "Skip frontend dependency installation and build?" "Y"; then
    SKIP_FRONTEND=1
  fi
fi

if [ "$SKIP_FRONTEND" != "1" ]; then
  need_cmd npm
  if [ -d "$ROOT_DIR/node_modules" ]; then
    echo "[INFO] node_modules directory already exists."
    if prompt_yes_no "Skip 'npm ci' and only run 'npm run build'?" "Y"; then
      echo "Building frontend..."
      (cd "$ROOT_DIR" && npm run build)
    else
      echo "Installing frontend dependencies..."
      (cd "$ROOT_DIR" && npm ci)
      echo "Building frontend..."
      (cd "$ROOT_DIR" && npm run build)
    fi
  else
    echo "Installing frontend dependencies..."
    (cd "$ROOT_DIR" && npm ci)
    echo "Building frontend..."
    (cd "$ROOT_DIR" && npm run build)
  fi

  # If Nginx deployment directory exists and is writable, sync dist files
  if [ -d "/var/www/html/fzvis" ] && [ -w "/var/www/html/fzvis" ]; then
    echo "[INFO] Updating Nginx deployment at /var/www/html/fzvis..."
    cp -r "$ROOT_DIR/dist/"* /var/www/html/fzvis/
  fi
else
  echo "[INFO] Skipping frontend build."
fi

# ============================================================
# 6. Dependencies: MSz and FFCz
# ============================================================
echo
echo "============================================================"
echo " 6. Dependencies: MSz and FFCz"
echo "============================================================"

OPT_DEPS_DIR="$ROOT_DIR/external"
mkdir -p "$OPT_DEPS_DIR"

# Check MSz
PYTHON_BIN="$(command -v python || command -v python3)"
PY_VER="$($PYTHON_BIN -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")' 2>/dev/null || echo "3.11")"
LOCAL_SITE="$FZVIS_ENV_DIR/local/lib/python$PY_VER/site-packages"
SPACK_PYTHON_SITE="$($PYTHON_BIN -c 'import site; print(site.getsitepackages()[0])' 2>/dev/null || echo "$LOCAL_SITE")"

mkdir -p "$LOCAL_SITE"
export PYTHONPATH="$SPACK_PYTHON_SITE:$LOCAL_SITE:${PYTHONPATH:-}"

# Clean any Spack view/lib from LD_LIBRARY_PATH to avoid GLIBCXX/libstdc++ conflicts with system tools (cmake, etc.)
CLEAN_LD=""
if [ -n "${LD_LIBRARY_PATH:-}" ]; then
  IFS=':' read -ra ADDR <<< "$LD_LIBRARY_PATH"
  for p in "${ADDR[@]}"; do
    if [[ "$p" != *".spack-env/view"* ]]; then
      CLEAN_LD="${CLEAN_LD:+$CLEAN_LD:}$p"
    fi
  done
fi
export LD_LIBRARY_PATH="$FZVIS_ENV_DIR/local/lib${CLEAN_LD:+:$CLEAN_LD}"

MSZ_INSTALLED=0
if $PYTHON_BIN -c "import msz; assert hasattr(msz, 'extract_critical_points')" >/dev/null 2>&1; then
  MSZ_INSTALLED=1
fi

if [ "$MSZ_INSTALLED" = "1" ]; then
  echo "[INFO] MSz is ALREADY INSTALLED and importable in Python."
  if prompt_yes_no "Skip building MSz?" "Y"; then
    BUILD_MSZ=0
  else
    BUILD_MSZ=1
  fi
else
  echo "[INFO] MSz is not installed (or not importable in Python)."
  if prompt_yes_no "Install MSz?" "Y"; then
    BUILD_MSZ=1
  else
    BUILD_MSZ=0
  fi
fi

if [ "$BUILD_MSZ" = "1" ]; then
  echo "Cloning and building MSz (branch 'fz' with Python bindings)..."
  clone_or_update "https://github.com/YuxiaoLi1234/MSz.git" "$OPT_DEPS_DIR/MSz" "fz"

  PYTHON_PREFIX="$($PYTHON_BIN -c 'import sys; print(sys.prefix)' 2>/dev/null || true)"
  (
    cd "$OPT_DEPS_DIR/MSz"
    mkdir -p build && cd build
    cmake \
      -DPython3_EXECUTABLE="$PYTHON_BIN" \
      ${PYTHON_PREFIX:+-DPython3_ROOT_DIR="$PYTHON_PREFIX"} \
      -DMSZ_PYTHON_INSTALL_DIR="$LOCAL_SITE" \
      -DCMAKE_INSTALL_PREFIX="$FZVIS_ENV_DIR/local" \
      -DCMAKE_INSTALL_RPATH="\$ORIGIN:$FZVIS_ENV_DIR/local/lib" \
      -DCMAKE_BUILD_WITH_INSTALL_RPATH=ON \
      -DMSZ_ENABLE_CUDA=OFF \
      ..
    make -j"$(nproc)"
    make install
  )

  # Copy compiled module msz*.so into Spack environment site-packages and LOCAL_SITE
  for so_file in "$OPT_DEPS_DIR/MSz/build"/msz*.so "$LOCAL_SITE"/msz*.so; do
    if [ -f "$so_file" ]; then
      cp -f "$so_file" "$LOCAL_SITE/" 2>/dev/null || true
      if [ -n "$SPACK_PYTHON_SITE" ] && [ -d "$SPACK_PYTHON_SITE" ] && [ -w "$SPACK_PYTHON_SITE" ]; then
        cp -f "$so_file" "$SPACK_PYTHON_SITE/" 2>/dev/null || true
      fi
    fi
  done

  # Also copy libMSz shared library next to msz extension and into local/lib.
  # With $ORIGIN in RPATH, placing libMSz next to msz*.so eliminates LD_LIBRARY_PATH dependency!
  for lib_file in "$OPT_DEPS_DIR/MSz/build"/libMSz*.so* "$FZVIS_ENV_DIR/local/lib"/libMSz*.so*; do
    if [ -f "$lib_file" ]; then
      cp -a "$lib_file" "$LOCAL_SITE/" 2>/dev/null || true
      if [ -n "$SPACK_PYTHON_SITE" ] && [ -d "$SPACK_PYTHON_SITE" ] && [ -w "$SPACK_PYTHON_SITE" ]; then
        cp -a "$lib_file" "$SPACK_PYTHON_SITE/" 2>/dev/null || true
      fi
    fi
  done

  # Place .pth file in Spack environment site-packages pointing to LOCAL_SITE as a fallback
  if [ -n "$SPACK_PYTHON_SITE" ] && [ -d "$SPACK_PYTHON_SITE" ] && [ -w "$SPACK_PYTHON_SITE" ]; then
    echo "$LOCAL_SITE" > "$SPACK_PYTHON_SITE/fzvis_msz.pth" 2>/dev/null || true
  fi

  # Verify import
  if $PYTHON_BIN -c "import msz; assert hasattr(msz, 'extract_critical_points')" >/dev/null 2>&1; then
    echo "[INFO] Verified: 'import msz' succeeded in Python!"
  else
    echo "[WARNING] 'import msz' verification failed after build."
    echo "          Diagnostics:"
    $PYTHON_BIN -c "import msz" || true
  fi
else
  echo "[INFO] Skipping MSz build."
fi

# Check FFCz
FFCZ_INSTALLED=0
if [ -x "$FZVIS_ENV_DIR/local/bin/ffcz" ] || [ -x "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz_cpu" ] || command -v ffcz >/dev/null 2>&1; then
  FFCZ_INSTALLED=1
fi

if [ "$FFCZ_INSTALLED" = "1" ]; then
  FFCZ_PATH="$(command -v ffcz 2>/dev/null || true)"
  if [ -z "$FFCZ_PATH" ] && [ -x "$FZVIS_ENV_DIR/local/bin/ffcz" ]; then
    FFCZ_PATH="$FZVIS_ENV_DIR/local/bin/ffcz"
  elif [ -z "$FFCZ_PATH" ]; then
    FFCZ_PATH="$OPT_DEPS_DIR/FFCz/CPU/build/ffcz_cpu"
  fi
  echo "[INFO] FFCz is ALREADY INSTALLED ($FFCZ_PATH)."
  if prompt_yes_no "Skip building FFCz?" "Y"; then
    BUILD_FFCZ=0
  else
    BUILD_FFCZ=1
  fi
else
  echo "[INFO] FFCz is not installed."
  if prompt_yes_no "Install FFCz?" "Y"; then
    BUILD_FFCZ=1
  else
    BUILD_FFCZ=0
  fi
fi

if [ "$BUILD_FFCZ" = "1" ]; then
  # Ensure PKG_CONFIG_PATH includes local, system multiarch, and standard prefixes
  ARCH_TRIPLET="$(gcc -dumpmachine 2>/dev/null || uname -m)-linux-gnu"
  for pcdir in \
    "$FZVIS_ENV_DIR/local/lib/pkgconfig" \
    "/usr/lib/$ARCH_TRIPLET/pkgconfig" \
    "/usr/lib/x86_64-linux-gnu/pkgconfig" \
    "/usr/lib/aarch64-linux-gnu/pkgconfig" \
    "/usr/lib64/pkgconfig" \
    "/usr/lib/pkgconfig" \
    "/usr/local/lib/pkgconfig" \
    "/usr/share/pkgconfig"; do
    if [ -d "$pcdir" ]; then
      case ":${PKG_CONFIG_PATH:-}:" in
        *":$pcdir:"*) ;;
        *) export PKG_CONFIG_PATH="${PKG_CONFIG_PATH:+$PKG_CONFIG_PATH:}$pcdir" ;;
      esac
    fi
  done

  # Check if required FFTW3 dependencies (fftw3, fftw3f) are available in pkg-config or local/Spack prefixes
  FFTW_AVAILABLE=0
  if pkg-config --exists fftw3 fftw3f 2>/dev/null; then
    FFTW_AVAILABLE=1
  elif [ -f "$FZVIS_ENV_DIR/local/lib/pkgconfig/fftw3.pc" ] && [ -f "$FZVIS_ENV_DIR/local/lib/pkgconfig/fftw3f.pc" ]; then
    FFTW_AVAILABLE=1
  elif spack find fftw 2>/dev/null | grep -q fftw; then
    FFTW_AVAILABLE=1
  fi

  if [ "$FFTW_AVAILABLE" != "1" ]; then
    echo "[WARNING] FFCz requires FFTW3 (single and double precision: fftw3 and fftw3f)."
    echo "          Missing fftw3/fftw3f pkg-config definitions."
    if prompt_yes_no "Download and install FFTW3 locally without root (into $FZVIS_ENV_DIR/local)?" "Y"; then
      echo "Downloading and building FFTW 3.3.10 locally (float & double)..."
      FFTW_SRC_DIR="$OPT_DEPS_DIR/fftw-3.3.10"
      mkdir -p "$OPT_DEPS_DIR"
      if [ ! -f "$OPT_DEPS_DIR/fftw-3.3.10.tar.gz" ]; then
        curl -fsSL "https://www.fftw.org/fftw-3.3.10.tar.gz" -o "$OPT_DEPS_DIR/fftw-3.3.10.tar.gz" || \
        wget -q "https://www.fftw.org/fftw-3.3.10.tar.gz" -O "$OPT_DEPS_DIR/fftw-3.3.10.tar.gz"
      fi
      if [ ! -d "$FFTW_SRC_DIR" ]; then
        tar -xzf "$OPT_DEPS_DIR/fftw-3.3.10.tar.gz" -C "$OPT_DEPS_DIR"
      fi
      mkdir -p "$FZVIS_ENV_DIR/local"
      # Build double precision (fftw3)
      echo "Building FFTW3 (double precision)..."
      (
        cd "$FFTW_SRC_DIR"
        ./configure --prefix="$FZVIS_ENV_DIR/local" --enable-shared --enable-threads
        make -j"$(nproc)"
        make install
      )
      # Build single precision (fftw3f)
      echo "Building FFTW3 (single precision)..."
      (
        cd "$FFTW_SRC_DIR"
        ./configure --prefix="$FZVIS_ENV_DIR/local" --enable-shared --enable-threads --enable-float
        make -j"$(nproc)"
        make install
      )
      export PKG_CONFIG_PATH="$FZVIS_ENV_DIR/local/lib/pkgconfig:${PKG_CONFIG_PATH:-}"
      export LD_LIBRARY_PATH="$FZVIS_ENV_DIR/local/lib:${LD_LIBRARY_PATH:-}"
      FFTW_AVAILABLE=1
      echo "[INFO] Successfully installed local FFTW3 and FFTW3F!"
    fi
  fi

  if [ "$FFTW_AVAILABLE" != "1" ]; then
    if ! prompt_yes_no "Attempt building FFCz anyway?" "N"; then
      BUILD_FFCZ=0
    fi
  fi
fi

if [ "$BUILD_FFCZ" = "1" ]; then
  echo "Cloning and building FFCz..."
  clone_or_update "https://github.com/guoxiliu/FFCz.git" "$OPT_DEPS_DIR/FFCz"
  (
    cd "$OPT_DEPS_DIR/FFCz/CPU"
    mkdir -p build && cd build
    cmake .. \
      -DCMAKE_BUILD_TYPE=Release \
      -DCMAKE_PREFIX_PATH="$FZVIS_ENV_DIR/local" \
      -DCMAKE_INSTALL_RPATH="$FZVIS_ENV_DIR/local/lib" \
      -DCMAKE_BUILD_WITH_INSTALL_RPATH=ON
    make -j"$(nproc)"
  )
  mkdir -p "$FZVIS_ENV_DIR/local/bin"
  if [ -f "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz_cpu" ]; then
    ln -sf "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz_cpu" "$FZVIS_ENV_DIR/local/bin/ffcz"
    ln -sf "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz_cpu" "$FZVIS_ENV_DIR/local/bin/ffcz_cpu"
    echo "[INFO] FFCz binary linked to $FZVIS_ENV_DIR/local/bin/ffcz and ffcz_cpu"
  elif [ -f "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz" ]; then
    ln -sf "$OPT_DEPS_DIR/FFCz/CPU/build/ffcz" "$FZVIS_ENV_DIR/local/bin/ffcz"
  fi

  # Verify FFCz execution
  if [ -x "$FZVIS_ENV_DIR/local/bin/ffcz" ] && ("$FZVIS_ENV_DIR/local/bin/ffcz" 2>&1 || true) | grep -qi "usage"; then
    echo "[INFO] Verified: FFCz binary executed successfully!"
  else
    echo "[WARNING] FFCz binary execution test failed. Please check build logs."
  fi
else
  echo "[INFO] Skipping FFCz build."
fi

